const BOARD = 0xb3141f;
const FRAME = 0xe2b04a;
const LETTER = 0xf8d870;

/**
 * A sign board facing +z in the site's frame, its middle at (x, y, z), at most `w` m wide and `h` m tall; the letters
 * only with `letters` (the board alone on low). Seen from the front the site's +x is on the right, so a word runs from
 * −x to +x.
 */
export function stallSign(s: Site, kind: StallKind, x: number, y: number, z: number, w: number, h: number, letters: boolean): void {
  const rows = WORDS[kind];
  const cols = rows[0].length;
  const px = Math.min(0.05, (w - 0.22) / cols, (h - 0.18) / rows.length);
  const bw = Math.max(cols * px + 0.22, w * 0.7);
  const bh = rows.length * px + 0.18;
  s.box(x, y, z - 0.01, bw + 0.08, bh + 0.08, 0.04, FRAME, 'petal');
  s.box(x, y, z + 0.01, bw, bh, 0.04, BOARD, 'petal');
  if (!letters) return;
  const x0 = x - (cols * px) / 2;
  const y0 = y + (rows.length * px) / 2;
  for (let r = 0; r < rows.length; r++) {
    const row = rows[r];
    let c = 0;
    while (c < cols) {
      if (row[c] !== '#') {
        c++;
        continue;
      }
      let e = c;
      while (e < cols && row[e] === '#') e++;
      s.box(x0 + ((c + e) / 2) * px, y0 - (r + 0.5) * px, z + 0.04, (e - c) * px, px, 0.03, LETTER, 'petal', { shade: 1.15 });
      c = e;
    }
  }
}
