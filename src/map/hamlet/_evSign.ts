/** A word's painted pixels as rectangles (columns c0‥c1, rows r0‥r1): runs along a row, grown down while the rows below repeat them. */
function rects(rows: readonly string[]): [number, number, number, number][] {
  const H = rows.length;
  const W = rows[0].length;
  const used = rows.map((r) => [...r].map(() => false));
  const paint = (r: number, c: number) => rows[r][c] === '#' && !used[r][c];
  const out: [number, number, number, number][] = [];
  for (let r = 0; r < H; r++)
    for (let c = 0; c < W; c++) {
      if (!paint(r, c)) continue;
      let c1 = c;
      while (c1 + 1 < W && paint(r, c1 + 1)) c1++;
      let r1 = r;
      const same = (row: number) => {
        for (let k = c; k <= c1; k++) if (!paint(row, k)) return false;
        return (c === 0 || !paint(row, c - 1)) && (c1 === W - 1 || !paint(row, c1 + 1));
      };
      while (r1 + 1 < H && same(r1 + 1)) r1++;
      for (let rr = r; rr <= r1; rr++) for (let k = c; k <= c1; k++) used[rr][k] = true;
      out.push([c, c1, r, r1]);
    }
  return out;
}

/**
 * A word in raised letters on the +z face of a board (the builder's frame:
 * the board across x at z), centred on (x, y), each pixel `px` m, reading
 * left to right from the front.
 */
export function signWord(L: Local, word: keyof typeof EV_WORDS, x: number, y: number, z: number, px: number, color: number): void {
  const rows = EV_WORDS[word];
  const w = rows[0].length * px;
  const h = rows.length * px;
  for (const [c0, c1, r0, r1] of rects(rows)) {
    const u = ((c0 + c1 + 1) / 2) * px - w / 2;
    const v = h / 2 - ((r0 + r1 + 1) / 2) * px;
    L.box(x + u, y + v, z + 0.02, (c1 - c0 + 1) * px, (r1 - r0 + 1) * px, 0.04, color, 'mapBark', 1.08);
  }
}
